#include <array>

auto quxlang::parse_cpu_attribute_stem(std::string_view stem) -> std::optional< std::pair< cpu, std::string > >
{
    constexpr std::array< std::pair< std::string_view, cpu >, 7 > cpu_prefixes{
        std::pair{std::string_view{"X86_"}, cpu::x86_32},
        std::pair{std::string_view{"X64_"}, cpu::x86_64},
        std::pair{std::string_view{"ARM32_"}, cpu::arm_32},
        std::pair{std::string_view{"ARM64_"}, cpu::arm_64},
        std::pair{std::string_view{"RISCV32_"}, cpu::riscv_32},
        std::pair{std::string_view{"RISCV64_"}, cpu::riscv_64},
        std::pair{std::string_view{"Z_ARCH_"}, cpu::z_arch},
    };

    for (std::pair< std::string_view, cpu > const& cpu_prefix : cpu_prefixes)
    {
        if (!stem.starts_with(cpu_prefix.first))
        {
            continue;
        }

        std::string_view const attribute = stem.substr(cpu_prefix.first.size());
        std::map< cpu, cpu_attribute_catalog >::const_iterator const catalog_iter = cpu_attributes.find(cpu_prefix.second);
        if (catalog_iter == cpu_attributes.end())
        {
            return std::nullopt;
        }

        constexpr std::string_view feature_prefix = "FEATURE_";
        if (attribute.starts_with(feature_prefix) &&
            catalog_iter->second.stable_features.contains(std::string(attribute.substr(feature_prefix.size()))))
        {
            return std::pair{cpu_prefix.second, std::string(attribute)};
        }

        constexpr std::string_view perf_prefix = "PERF_";
        if (attribute.starts_with(perf_prefix) &&
            catalog_iter->second.stable_perf.contains(std::string(attribute.substr(perf_prefix.size()))))
        {
            return std::pair{cpu_prefix.second, std::string(attribute)};
        }

        return std::nullopt;
    }

    return std::nullopt;
}

auto quxlang::format_cpu_attribute_stem(cpu cpu_type, std::string_view attribute) -> std::string
{
    std::string_view cpu_prefix;
    switch (cpu_type)
    {
    case cpu::x86_32: cpu_prefix = "X86"; break;
    case cpu::x86_64: cpu_prefix = "X64"; break;
    case cpu::arm_32: cpu_prefix = "ARM32"; break;
    case cpu::arm_64: cpu_prefix = "ARM64"; break;
    case cpu::riscv_32: cpu_prefix = "RISCV32"; break;
    case cpu::riscv_64: cpu_prefix = "RISCV64"; break;
    case cpu::z_arch: cpu_prefix = "Z_ARCH"; break;
    case cpu::none: throw std::invalid_argument("A CPU attribute requires a CPU family");
    }

    std::string result(cpu_prefix);
    result += '_';
    result += attribute;
    if (!parse_cpu_attribute_stem(result).has_value())
    {
        throw std::invalid_argument("Unknown stable CPU attribute: " + result);
    }
    return result;
}

auto quxlang::is_cpu_attribute_enabled_name(std::string_view name) -> bool
{
    constexpr std::string_view suffix = "_ENABLED";
    return name.ends_with(suffix) && parse_cpu_attribute_stem(name.substr(0, name.size() - suffix.size())).has_value();
}

